import os
import tempfile
import unittest
from unittest.mock import patch
from PyQt6.QtCore import QPoint

os.environ.setdefault("QT_QPA_PLATFORM", "offscreen")

import erica_secure_text_editor as appmod


class EricaAppTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.app = appmod.QApplication.instance() or appmod.QApplication([])

    def setUp(self):
        self.temp_dir = tempfile.TemporaryDirectory()
        appmod.CONFIG_PATH = self.temp_dir.name
        appmod.CONFIG_FILE = os.path.join(self.temp_dir.name, "config.json")
        appmod.RECOVERY_FILE = os.path.join(self.temp_dir.name, "recovery.enc")
        appmod._TEST_RECOVERY_KEY_PROTECTOR = lambda secret: f"protected::{secret}"
        appmod._TEST_RECOVERY_KEY_UNPROTECTOR = lambda secret: secret.split("protected::", 1)[1]
        self.hardened_paths = []
        appmod._TEST_HARDEN_PRIVATE_FILE_HOOK = self.hardened_paths.append
        self.window = appmod.MainWindow()

    def tearDown(self):
        self.window.close()
        appmod._TEST_RECOVERY_KEY_PROTECTOR = None
        appmod._TEST_RECOVERY_KEY_UNPROTECTOR = None
        appmod._TEST_HARDEN_PRIVATE_FILE_HOOK = None
        self.temp_dir.cleanup()

    def test_encrypt_roundtrip(self):
        encrypted = appmod.encrypt_text("hello", "Passw0rd!")
        self.assertEqual(appmod.decrypt_text(encrypted, "Passw0rd!"), "hello")

    def test_malformed_encrypted_data_rejected_before_key_derivation(self):
        for size in [0, 48, 64, 79, 81, 95]:
            with self.subTest(size=size), patch.object(appmod, "derive_key") as derive:
                with self.assertRaises(ValueError):
                    appmod.decrypt_bytes(b"x" * size, "Passw0rd!")
                derive.assert_not_called()

    def test_known_legacy_ciphertext_remains_readable(self):
        # Fixed fixture generated by the pre-Rust AES-CBC/HMAC implementation.
        encrypted = bytes.fromhex(
            "bfb7b408993be6aa29866c14019a484b773243a22fa7722bb7ee6e5140e42fb64d"
            "74dc1f02e4232fc8452317b9ee4a4690867babe3a40efcab119967997dd8644d6"
            "6113e14619fa594c0c82860eba936775ddca663f8b4e09d9830fcee49c1cd"
        )
        self.assertEqual(appmod.decrypt_text(encrypted, "Legacy-fixture-123!"),
                         "Legacy compatibility fixture")

    def test_tampered_and_wrong_password_still_fail_authentication(self):
        encrypted = appmod.encrypt_text("private", "Passw0rd!")
        tampered = encrypted[:-1] + bytes([encrypted[-1] ^ 1])
        for data, password in [(tampered, "Passw0rd!"), (encrypted, "wrong")]:
            with self.subTest(password=password), self.assertRaises(appmod.IntegrityError):
                appmod.decrypt_text(data, password)

    def test_silent_save_does_not_retain_password(self):
        path = os.path.join(self.temp_dir.name, "silent.erica")
        self.window.current_editor.setPlainText("silent save")
        with patch.object(appmod.QFileDialog, "getSaveFileName", return_value=(path, "")), \
             patch.object(self.window, "prompt_password", return_value="Passw0rd!"):
            self.assertTrue(self.window.silent_save(0))
        self.assertIsNone(self.window.open_documents[0].get("password"))
        with open(path, "rb") as handle:
            self.assertIn("silent save", appmod.decrypt_text(handle.read(), "Passw0rd!"))

    def test_failed_silent_save_keeps_path_and_modified_state(self):
        self.window.current_editor.setPlainText("unsaved")
        self.window.current_editor.document().setModified(True)
        path = os.path.join(self.temp_dir.name, "failed.erica")
        with patch.object(appmod.QFileDialog, "getSaveFileName", return_value=(path, "")), \
             patch.object(self.window, "prompt_password", return_value="Passw0rd!"), \
             patch.object(appmod, "atomic_write", side_effect=OSError("simulated failure")), \
             patch.object(appmod.QMessageBox, "critical"):
            self.assertFalse(self.window.silent_save(0))
        self.assertIsNone(self.window.open_documents[0]["path"])
        self.assertTrue(self.window.current_editor.document().isModified())

    def test_failed_resave_preserves_old_encrypted_bytes(self):
        path = os.path.join(self.temp_dir.name, "original.erica")
        original = appmod.encrypt_text("original", "Passw0rd!")
        with open(path, "wb") as handle:
            handle.write(original)
        self.window.set_current_file_path(path)
        self.window.current_editor.setPlainText("replacement")
        self.window.current_editor.document().setModified(True)
        with patch.object(self.window, "prompt_password", return_value="Passw0rd!"), \
             patch.object(appmod, "atomic_write", side_effect=OSError("simulated failure")), \
             patch.object(appmod.QMessageBox, "critical"):
            self.window.save_file()
        with open(path, "rb") as handle:
            self.assertEqual(handle.read(), original)
        self.assertTrue(self.window.current_editor.document().isModified())

    def test_recent_files_and_last_session(self):
        test_file = os.path.join(self.temp_dir.name, "sample.erica")
        with open(test_file, "wb") as handle:
            handle.write(b"data")

        appmod.save_recent_file(test_file)
        appmod.save_last_session_files([test_file])

        self.assertEqual(appmod.get_recent_files(), [test_file])
        self.assertEqual(appmod.get_last_session_files(), [test_file])

    def test_recovery_snapshot_roundtrip(self):
        self.window.current_editor.setPlainText("recover me")
        self.window.current_editor.document().setModified(True)
        self.window.autosave_recovery_snapshot()

        self.assertTrue(os.path.exists(appmod.RECOVERY_FILE))

        with open(appmod.RECOVERY_FILE, "rb") as handle:
            recovered = appmod.decrypt_bytes(handle.read(), appmod.get_recovery_key())
        self.assertIn("recover me", recovered.decode("utf-8"))

        config = appmod.load_config()
        self.assertNotIn("recovery_key", config)
        self.assertTrue(config["recovery_key_protected"].startswith("protected::"))
        self.assertIn(appmod.RECOVERY_FILE, self.hardened_paths)

    def test_save_and_resave_same_file(self):
        fd, path = tempfile.mkstemp(dir=self.temp_dir.name, suffix=".erica")
        os.close(fd)
        os.unlink(path)

        with patch.object(appmod.QMessageBox, "question", return_value=appmod.QMessageBox.StandardButton.No), \
             patch.object(appmod.QFileDialog, "getSaveFileName", return_value=(path, "Erica Secure Files (*.erica)")):
            self.window.prompt_password = lambda *args, **kwargs: "Passw0rd!"
            self.window.current_editor.setPlainText("first")
            self.window.save_as_file()
            self.window.current_editor.setPlainText("second")
            self.window.save_file()

        with open(path, "rb") as handle:
            decrypted = appmod.decrypt_text(handle.read(), "Passw0rd!")
        self.assertIn("second", decrypted)
        self.assertIsNone(self.window.get_current_password())

    def test_get_recovery_key_migrates_legacy_plaintext_key(self):
        appmod.save_config({"recovery_key": "legacy-secret"})

        recovered_key = appmod.get_recovery_key()

        self.assertEqual(recovered_key, "legacy-secret")
        config = appmod.load_config()
        self.assertNotIn("recovery_key", config)
        self.assertEqual(config["recovery_key_protected"], "protected::legacy-secret")
        self.assertIn(appmod.CONFIG_FILE, self.hardened_paths)

    def test_open_external_link_blocks_unsafe_scheme(self):
        with patch.object(appmod.QMessageBox, "warning") as warning_mock, \
             patch.object(appmod.QDesktopServices, "openUrl") as open_mock:
            self.window.openExternalLink("file:///C:/secret.txt")

        warning_mock.assert_called_once()
        open_mock.assert_not_called()

    def test_open_external_link_allows_https(self):
        with patch.object(appmod.QMessageBox, "warning") as warning_mock, \
             patch.object(appmod.QDesktopServices, "openUrl") as open_mock:
            self.window.openExternalLink("https://example.com")

        warning_mock.assert_not_called()
        open_mock.assert_called_once()

    def test_editor_anchor_blocks_unsafe_link(self):
        editor = appmod.ClickableTextBrowser()

        with patch.object(editor, "anchorAt", return_value="file:///C:/secret.txt"), \
             patch.object(appmod.QMessageBox, "warning") as warning_mock, \
             patch.object(appmod.QDesktopServices, "openUrl") as open_mock:
            class _Event:
                def button(self):
                    return appmod.Qt.MouseButton.LeftButton

                def pos(self):
                    return QPoint(0, 0)

            editor.mouseReleaseEvent(_Event())

        warning_mock.assert_called_once()
        open_mock.assert_not_called()

    def test_save_config_hardens_private_file(self):
        appmod.save_config({"theme": "dark"})
        self.assertIn(appmod.CONFIG_FILE, self.hardened_paths)

    def test_save_adds_erica_extension_when_missing(self):
        path = os.path.join(self.temp_dir.name, "notes")

        with patch.object(appmod.QMessageBox, "question", return_value=appmod.QMessageBox.StandardButton.No), \
             patch.object(appmod.QFileDialog, "getSaveFileName", return_value=(path, "Erica Secure Files (*.erica)")):
            self.window.prompt_password = lambda *args, **kwargs: "Passw0rd!"
            self.window.current_editor.setPlainText("extension test")
            self.window.save_as_file()

        saved_path = f"{path}{appmod.DOCUMENT_EXTENSION}"
        self.assertTrue(os.path.exists(saved_path))

    def test_timeout_single_shutdown(self):
        calls = {"warning": 0, "quit": 0}
        self.window.remaining_time = 1

        with patch.object(appmod.QMessageBox, "warning", side_effect=lambda *args, **kwargs: calls.__setitem__("warning", calls["warning"] + 1) or appmod.QMessageBox.StandardButton.Ok), \
             patch.object(self.app, "quit", side_effect=lambda: calls.__setitem__("quit", calls["quit"] + 1)):
            self.window.handle_timeout_tick()
            self.window.handle_timeout_tick()

        self.assertEqual(calls["warning"], 1)
        self.assertEqual(calls["quit"], 1)

    def test_table_crud_and_merge_split(self):
        editor = self.window.current_editor
        cursor = editor.textCursor()
        table_format = appmod.QTextTableFormat()
        table_format.setBorder(1)
        table = cursor.insertTable(2, 2, table_format)

        editor.setTextCursor(table.cellAt(0, 0).firstCursorPosition())
        self.window.insert_table_row_below()
        editor.setTextCursor(table.cellAt(0, 0).firstCursorPosition())
        self.window.insert_table_column_right()
        self.assertEqual((table.rows(), table.columns()), (3, 3))

        start = table.cellAt(0, 0).firstCursorPosition()
        end = table.cellAt(0, 1).lastCursorPosition()
        start.setPosition(end.position(), appmod.QTextCursor.MoveMode.KeepAnchor)
        editor.setTextCursor(start)
        self.window.merge_selected_table_cells()
        merged_cell = table.cellAt(0, 0)
        self.assertEqual((merged_cell.rowSpan(), merged_cell.columnSpan()), (1, 2))

        editor.setTextCursor(merged_cell.firstCursorPosition())
        self.window.split_current_table_cell()
        self.assertEqual((table.cellAt(0, 0).rowSpan(), table.cellAt(0, 0).columnSpan()), (1, 1))

    def test_close_tab_rebinds_toolbars_to_surviving_document(self):
        first = self.window.current_editor
        self.window.add_new_tab(content="Surviving document")
        second = self.window.current_editor
        self.window.tabs.setCurrentIndex(0)
        self.window.close_tab(0)
        self.assertIs(self.window.current_editor, second)
        self.assertIs(self.window.font_toolbar.editor, second)
        self.assertIs(self.window.table_toolbar.editor, second)
        second.selectAll()
        self.window.apply_bold()
        self.assertEqual(second.currentCharFormat().fontWeight(), appmod.QFont.Weight.Bold)
        self.assertFalse(first.document().isModified())
        second.document().setModified(False)

    def test_column_management_keeps_fresh_equal_widths_and_single_undo(self):
        toolbar = self.window.table_toolbar
        table = toolbar.insert_table(2, 2)
        before = self.window.current_editor.toHtml()
        self.window.insert_table_column_right()
        constraints = table.format().columnWidthConstraints()
        self.assertEqual(len(constraints), 3)
        self.assertTrue(all(abs(width.rawValue() - 100 / 3) < .001 for width in constraints))
        self.window.current_editor.undo()
        self.assertEqual(before, self.window.current_editor.toHtml())

    def insert_table_through_menu(self, rows=2, columns=2):
        def accept_dimensions(dialog):
            from PyQt6.QtWidgets import QSpinBox
            dialog.findChild(QSpinBox, "rows").setValue(rows)
            dialog.findChild(QSpinBox, "columns").setValue(columns)
            return appmod.QDialog.DialogCode.Accepted

        with patch.object(appmod.QDialog, "exec", accept_dimensions):
            action = next(action for action in self.window.findChildren(appmod.QAction)
                          if action.text() == "Insert Table")
            action.trigger()
        table = self.window.current_editor.textCursor().currentTable()
        self.assertIsNotNone(table, "Insert Table must leave the editor cursor inside the table")
        return table

    def test_menu_insert_table_visible_editable_and_undoable(self):
        editor = self.window.current_editor
        table = self.insert_table_through_menu()
        self.assertEqual((table.rows(), table.columns()), (2, 2))
        self.assertEqual(table.format().width().type(), appmod.QTextLength.Type.PercentageLength)
        self.assertEqual(table.format().width().rawValue(), 100)
        self.assertEqual(len(table.format().columnWidthConstraints()), 2)
        editor.insertPlainText("First cell")
        self.assertIn("First cell", table.cellAt(0, 0).firstCursorPosition().block().text())
        editor.undo()
        editor.undo()
        self.assertEqual(len(editor.document().rootFrame().childFrames()), 0)
        editor.redo()
        self.assertEqual(len(editor.document().rootFrame().childFrames()), 1)

    def test_menu_insert_cancel_does_not_change_document(self):
        with patch.object(appmod.QDialog, "exec", return_value=appmod.QDialog.DialogCode.Rejected):
            self.window.table_toolbar.insert_table_dialog()
        self.assertFalse(self.window.current_editor.document().isModified())
        self.assertEqual(len(self.window.current_editor.document().rootFrame().childFrames()), 0)

    def test_insert_then_edit_rows_and_columns(self):
        table = self.insert_table_through_menu()
        self.window.insert_table_row_below()
        self.window.insert_table_column_right()
        self.assertEqual((table.rows(), table.columns()), (3, 3))
        self.window.delete_table_row()
        self.window.delete_table_column()
        self.assertEqual((table.rows(), table.columns()), (2, 2))

    def test_delete_table_preserves_surrounding_text_and_undo(self):
        editor = self.window.current_editor
        editor.setPlainText("Before\nAfter")
        cursor = editor.textCursor()
        cursor.setPosition(len("Before\n"))
        editor.setTextCursor(cursor)
        self.insert_table_through_menu()
        self.window.delete_current_table()
        self.assertEqual(len(editor.document().rootFrame().childFrames()), 0)
        self.assertIn("Before", editor.toPlainText())
        self.assertIn("After", editor.toPlainText())
        editor.undo()
        self.assertEqual(len(editor.document().rootFrame().childFrames()), 1)

    def test_deleting_last_row_or_column_removes_table(self):
        for operation in [self.window.delete_table_row, self.window.delete_table_column]:
            with self.subTest(operation=operation.__name__):
                self.window.current_editor.clear()
                self.insert_table_through_menu(1, 1)
                operation()
                self.assertEqual(len(self.window.current_editor.document().rootFrame().childFrames()), 0)

    def test_empty_table_is_included_in_recovery(self):
        self.insert_table_through_menu()
        documents = self.window.build_recovery_payload()["documents"]
        self.assertEqual(len(documents), 1)
        self.assertIn("<table", documents[0]["html"])

    def test_table_survives_encrypted_html_roundtrip(self):
        self.insert_table_through_menu()
        self.window.current_editor.insertPlainText("Protected cell")
        html = self.window.current_editor.toHtml()
        restored = appmod.decrypt_text(appmod.encrypt_text(html, "Passw0rd!"), "Passw0rd!")
        self.window.add_new_tab(content=restored, content_is_html=True)
        tables = self.window.current_editor.document().rootFrame().childFrames()
        self.assertEqual(len(tables), 1)
        self.assertEqual((tables[0].rows(), tables[0].columns()), (2, 2))
        self.assertIn("Protected cell", self.window.current_editor.toPlainText())


if __name__ == "__main__":
    unittest.main()
