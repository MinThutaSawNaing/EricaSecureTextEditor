def reference_check(token):
    """Independent ABI 2 typo-check algorithm (not an authentication value)."""
    digest = hashlib.sha256(b"ERICAORG\x00CHECK\x01" + token.encode("ascii")).digest()
    return f"{int.from_bytes(digest[:8], 'big') % 100000:05d}"


def reference_key(tokens, salt):
    """Independent documented v1 KDF, never a production-module private call."""
    material = b"ERICAORG\x00TOKENS\x01" + "".join(tokens).encode("ascii")
    return Scrypt(salt=salt, length=32, n=2**15, r=8, p=1).derive(material)


def windows_dpapi(data, *, protect):
    """Independent Windows API oracle for native DPAPI interoperability."""
    from ctypes import wintypes

    class Blob(ctypes.Structure):
        _fields_ = [("size", wintypes.DWORD),
                    ("data", ctypes.POINTER(ctypes.c_ubyte))]

    crypt32 = ctypes.WinDLL("crypt32.dll", use_last_error=True)
    kernel32 = ctypes.WinDLL("kernel32.dll", use_last_error=True)
    function = crypt32.CryptProtectData if protect else crypt32.CryptUnprotectData
    function.argtypes = [ctypes.POINTER(Blob), ctypes.c_void_p,
                         ctypes.POINTER(Blob), ctypes.c_void_p, ctypes.c_void_p,
                         wintypes.DWORD, ctypes.POINTER(Blob)]
    function.restype = wintypes.BOOL
    kernel32.LocalFree.argtypes = [ctypes.c_void_p]
    kernel32.LocalFree.restype = ctypes.c_void_p
    buffer = ctypes.create_string_buffer(data, max(1, len(data)))
    source = Blob(len(data), ctypes.cast(buffer, ctypes.POINTER(ctypes.c_ubyte)))
    result = Blob()
    try:
        # Current user, UI forbidden; no CRYPTPROTECT_LOCAL_MACHINE flag.
        if not function(ctypes.byref(source), None, None, None, None,
                        1, ctypes.byref(result)):
            raise ctypes.WinError(ctypes.get_last_error())
        return ctypes.string_at(result.data, result.size)
    finally:
        ctypes.memset(buffer, 0, len(data))
        if result.data:
            ctypes.memset(result.data, 0, result.size)
            kernel32.LocalFree(result.data)


class TokenTests(unittest.TestCase):
    def test_strict_valid_tokens_and_order(self):
        self.assertEqual(org.validate_tokens(*TOKENS), TOKENS)
        self.assertEqual(org.validate_tokens(*TOKENS[::-1]), TOKENS[::-1])
        self.assertEqual(org.validate_tokens("0" * 16, "9" * 16), ("0" * 16, "9" * 16))

    def test_invalid_token_inputs(self):
        invalid = [None, 1234567890123456, b"0123456789012345", [], {},
                   "", "0" * 15, "0" * 17, " " + "0" * 15,
                   "0" * 15 + "\n", "+" + "0" * 15, "0" * 15 + ".",
                   "٠" * 16, "０" * 16, "²" * 16, "a" * 16,
                   "0" * 15 + "\x00", "0" * 15 + "é"]
        for value in invalid:
            with self.subTest(value=repr(value)):
                for pair in ((value, TOKENS[1]), (TOKENS[0], value)):
                    with self.assertRaises(ValueError):
                        org.validate_tokens(*pair)
                with self.assertRaises(ValueError):
                    org.check_value(value)
        with self.assertRaisesRegex(ValueError, "distinct"):
            org.validate_tokens(TOKENS[0], TOKENS[0])

    def test_check_value_format_and_documented_algorithm(self):
        for token in (*TOKENS, "0000000000000006", "0000000000000000"):
            expected = reference_check(token)
            self.assertEqual(org.check_value(token), expected)
            self.assertRegex(org.check_value(token), r"\A[0-9]{5}\Z")
        self.assertEqual(tuple(map(org.check_value, TOKENS)), FIXTURE_CHECKS)
        self.assertEqual(org.check_value("0000000000000006"), "05553")
        self.assertNotEqual(org.check_value(TOKENS[0]), org.check_value(TOKENS[1]))

    def test_check_validation(self):
        first, second = map(org.check_value, TOKENS)
        self.assertEqual(org.validate_check_values(TOKENS[0], first, TOKENS[1], second), TOKENS)
        for checks in ((second, first), ("0" * 5, second), (first, "9" * 5), OLD_CHECKS):
            with self.subTest(checks=checks), self.assertRaises(ValueError):
                org.validate_check_values(TOKENS[0], checks[0], TOKENS[1], checks[1])
        with self.assertRaises(ValueError):
            org.validate_check_values(TOKENS[0], first, TOKENS[0], first)

    def test_check_input_errors(self):
        first, second = map(org.check_value, TOKENS)
        invalid = [None, 123, b"03129", "", "3129", "003129",
                   *OLD_CHECKS, "abcde", "0312A", "０" * 5, "٠" * 5,
                   "²" * 5, " 3129", "03129 ", "+3129", "031.9",
                   "0312\n", "0312\x00"]
        for check in invalid:
            for checks in ((check, second), (first, check)):
                with self.subTest(check=repr(check)), self.assertRaises(ValueError):
                    org.validate_check_values(TOKENS[0], checks[0], TOKENS[1], checks[1])
        for pair in (("invalid", TOKENS[1]), (TOKENS[0], "invalid")):
            with self.subTest(pair=pair), self.assertRaises(ValueError):
                org.validate_check_values(pair[0], first, pair[1], second)

    def test_generate_tokens(self):
        pairs = [org.generate_tokens() for _ in range(32)]
        for pair in pairs:
            self.assertIsInstance(pair, tuple)
            self.assertEqual(org.validate_tokens(*pair), pair)
        self.assertEqual(len(set(pairs)), len(pairs))

    def test_generated_tokens_cover_decimal_positions_and_leading_zero(self):
        # Test observable output instead of replacing Python's random source.
        # 512 independent tokens miss a leading zero with probability < 4e-24.
        pairs = [org.generate_tokens() for _ in range(256)]
        tokens = [token for pair in pairs for token in pair]
        self.assertEqual(len(set(tokens)), len(tokens))
        self.assertTrue(any(token.startswith("0") for token in tokens))
        for pair in pairs:
            self.assertEqual(org.validate_tokens(*pair), pair)
        for index in range(16):
            self.assertEqual({token[index] for token in tokens}, set("0123456789"))


class EncryptionTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.raw = b"Binary\x00\xff\r\n" + "Private text: café 日本語".encode("utf-8")
        cls.encrypted = org.encrypt_bytes(cls.raw, TOKENS)

    def test_round_trip_binary_empty_and_large(self):
        self.assertEqual(org.decrypt_bytes(self.encrypted, TOKENS), self.raw)
        for raw in (b"", bytes(range(256)) * 4096):
            with self.subTest(length=len(raw)):
                self.assertEqual(org.decrypt_bytes(org.encrypt_bytes(raw, TOKENS), TOKENS), raw)

    def test_fixed_header_and_no_token_or_check_metadata(self):
        self.assertEqual(len(self.encrypted), HEADER_SIZE + len(self.raw) + 16)
        magic, version, salt, nonce = struct.unpack(">8sB16s12s", self.encrypted[:HEADER_SIZE])
        self.assertEqual(magic, b"ERICAORG")
        self.assertEqual(version, 1)
        self.assertEqual(len(salt), 16)
        self.assertEqual(len(nonce), 12)
        for token in TOKENS:
            self.assertNotIn(token.encode("ascii"), self.encrypted)
            self.assertNotIn(org.check_value(token).encode("ascii"), self.encrypted)
        self.assertNotIn(self.raw, self.encrypted)

    def test_fresh_salt_and_nonce(self):
        second = org.encrypt_bytes(self.raw, TOKENS)
        self.assertNotEqual(second, self.encrypted)
        self.assertNotEqual(second[9:25], self.encrypted[9:25])
        self.assertNotEqual(second[25:37], self.encrypted[25:37])
        self.assertEqual(org.decrypt_bytes(second, TOKENS), self.raw)

    def test_rust_ciphertext_decrypts_with_independent_python_reference(self):
        key = reference_key(TOKENS, self.encrypted[9:25])
        self.assertEqual(AESGCM(key).decrypt(
            self.encrypted[25:37], self.encrypted[37:], self.encrypted[:37]), self.raw)

    def test_python_reference_ciphertext_decrypts_in_rust(self):
        salt, nonce = bytes(range(16)), bytes(range(16, 28))
        header = struct.pack(">8sB16s12s", b"ERICAORG", 1, salt, nonce)
        for pair, raw in ((TOKENS, self.raw), (TOKENS[::-1], b"")):
            encrypted = header + AESGCM(reference_key(pair, salt)).encrypt(nonce, raw, header)
            with self.subTest(pair=pair, raw=raw):
                self.assertEqual(org.decrypt_bytes(encrypted, pair), raw)

    def test_permanent_legacy_python_fixture(self):
        self.assertEqual(tuple(map(org.check_value, TOKENS)), FIXTURE_CHECKS)
        self.assertEqual(org.validate_check_values(
            TOKENS[0], FIXTURE_CHECKS[0], TOKENS[1], FIXTURE_CHECKS[1]), TOKENS)
        self.assertEqual(org.decrypt_bytes(LEGACY_CIPHERTEXT, TOKENS), LEGACY_RAW)

    def test_wrong_pair_wrong_each_token_and_reversed_order(self):
        for pair in (TOKENS[::-1], (OTHER, TOKENS[1]), (TOKENS[0], OTHER),
                     ("1" * 16, "2" * 16)):
            with self.subTest(pair=pair), self.assertRaises(org.OrganizationIntegrityError) as caught:
                org.decrypt_bytes(self.encrypted, pair)
            for token in pair + TOKENS:
                self.assertNotIn(token, str(caught.exception))

    def test_malformed_and_unknown_version(self):
        malformed = [None, "ERICAORG", bytearray(self.encrypted), b"", b"not a file",
                     b"OTHERORG" + self.encrypted[8:]]
        malformed.extend(self.encrypted[:length] for length in range(HEADER_SIZE + 16))
        malformed.extend(self.encrypted[:8] + bytes([version]) + self.encrypted[9:]
                         for version in (0, 2, 255))
        for data in malformed:
            with self.subTest(data=repr(data)[:80]), self.assertRaises(org.InvalidOrganizationFile):
                org.decrypt_bytes(data, TOKENS)

    def test_magic_routing_includes_unknown_and_truncated_versions(self):
        for data in (self.encrypted, b"ERICAORG", b"ERICAORG\xff"):
            self.assertTrue(org.is_organization_data(data))
        for data in (b"", b"ERICAOR", b"xERICAORG", b"ericaorg", None,
                     "ERICAORG", 1, bytearray(b"ERICAORG"), memoryview(b"ERICAORG")):
            self.assertFalse(org.is_organization_data(data))

    def test_tamper_salt_nonce_ciphertext_tag_truncation_and_append(self):
        changed = []
        for offset in (9, 24, 25, 36, 37, len(self.encrypted) - 17, len(self.encrypted) - 1):
            data = bytearray(self.encrypted)
            data[offset] ^= 1
            changed.append(bytes(data))
        changed.extend((self.encrypted[:-1], self.encrypted + b"\x00"))
        for data in changed:
            with self.subTest(data=data.hex()), self.assertRaises(org.OrganizationIntegrityError):
                org.decrypt_bytes(data, TOKENS)

    def test_full_header_aad_required(self):
        key = reference_key(TOKENS, self.encrypted[9:25])
        nonce, header = self.encrypted[25:37], self.encrypted[:37]
        for aad in (None, header[8:], header[:9]):
            data = header + AESGCM(key).encrypt(nonce, self.raw, aad)
            with self.subTest(aad=aad), self.assertRaises(org.OrganizationIntegrityError):
                org.decrypt_bytes(data, TOKENS)

    def test_pair_and_plaintext_input_errors(self):
        for pair in (None, [], list(TOKENS), TOKENS[:1], TOKENS + (OTHER,),
                     (TOKENS[0], TOKENS[0]), (TOKENS[0], "bad")):
            for operation in (lambda: org.encrypt_bytes(b"x", pair),
                              lambda: org.decrypt_bytes(self.encrypted, pair),
                              lambda: org.protect_tokens(pair)):
                with self.subTest(pair=pair), self.assertRaises(ValueError):
                    operation()
        for raw in (None, "text", 123, bytearray(b"x"), memoryview(b"x")):
            with self.subTest(raw=raw), self.assertRaises(ValueError):
                org.encrypt_bytes(raw, TOKENS)

    def test_exception_hierarchy(self):
        self.assertTrue(issubclass(org.InvalidOrganizationFile, ValueError))
        self.assertTrue(issubclass(org.OrganizationIntegrityError, ValueError))


