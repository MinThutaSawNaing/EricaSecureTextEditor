    def _set_visible(self, visible):
        echo = QLineEdit.EchoMode.Normal if visible else QLineEdit.EchoMode.Password
        for field in self.token_inputs:
            field.setEchoMode(echo)

    def generate_pair(self):
        try:
            tokens = organization.generate_tokens()
        except (ValueError, OSError, RuntimeError) as exc:
            QMessageBox.warning(self, "Organization Setup", str(exc))
            return
        for token, field in zip(tokens, self.token_inputs):
            field.setText(token)
        self.show_tokens.setChecked(True)
        self.backed_up.setChecked(False)

    def _refresh_check(self, index, token):
        self.backed_up.setChecked(False)
        status = "hint"
        message = "Requires exactly 16 digits (0-9). Leading zeros matter."
        try:
            value = organization.check_value(token)
            status, message = "ready", "16 digits entered. Compare the check with your trusted backup."
        except ValueError:
            value = ""
            if token:
                status = "error"
                message = f"Warning: requires exactly 16 digits (0-9); {len(token)} characters entered."
        except (OSError, RuntimeError):
            value = ""
            status, message = "error", "Warning: the Rust backend could not generate a check. Rebuild the native DLL."
        self.check_inputs[index].setText(value)
        self.copy_buttons[index].setEnabled(bool(value))
        hint = self.token_warnings[index]
        hint.setText(message)
        hint.setProperty("status", status)
        self.token_inputs[index].setProperty("invalid", status == "error")
        for widget in (hint, self.token_inputs[index]):
            widget.style().unpolish(widget)
            widget.style().polish(widget)

    def _copy_check(self, index):
        value = self.check_inputs[index].text()
        if value:
            QApplication.clipboard().setText(value)

    def validate_and_accept(self):
        try:
            values = [field.text() for field in self.token_inputs]
            checks = [field.text() for field in self.check_inputs]
            organization.validate_check_values(values[0], checks[0], values[1], checks[1])
            if not self.backed_up.isChecked():
                raise ValueError("Confirm that you have securely backed up both tokens and check values.")
        except (ValueError, OSError, RuntimeError) as exc:
            QMessageBox.warning(self, "Organization Setup", str(exc))
            return
        self.tokens = tuple(values)
        self.accept()

    def clear_fields(self):
        self.tokens = None
        for field in self.token_inputs + self.check_inputs:
            field.clear()