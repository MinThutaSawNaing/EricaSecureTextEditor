"""Organization enrollment UI; security operations remain in the Rust backend."""

from PyQt6.QtCore import QPointF, Qt
from PyQt6.QtGui import QColor, QPainter, QPalette, QPen
from PyQt6.QtWidgets import (
    QApplication, QCheckBox, QDialog, QDialogButtonBox, QFormLayout,
    QHBoxLayout, QLabel, QLineEdit, QMessageBox, QPushButton, QStyle,
    QStyleOptionButton, QVBoxLayout,
)

import erica_organization as organization


class _VisibleCheckBox(QCheckBox):
    """Keep native checkbox behavior with a theme-independent painted checkmark."""

    def paintEvent(self, event):
        super().paintEvent(event)
        if not self.isChecked():
            return
        option = QStyleOptionButton()
        self.initStyleOption(option)
        rect = self.style().subElementRect(QStyle.SubElement.SE_CheckBoxIndicator, option, self)
        painter = QPainter(self)
        painter.setRenderHint(QPainter.RenderHint.Antialiasing)
        pen = QPen(QColor(self.property("checkmarkColor")), 2.2)
        pen.setCapStyle(Qt.PenCapStyle.RoundCap)
        pen.setJoinStyle(Qt.PenJoinStyle.RoundJoin)
        painter.setPen(pen)
        painter.drawLine(QPointF(rect.left() + rect.width() * .23, rect.top() + rect.height() * .51),
                         QPointF(rect.left() + rect.width() * .43, rect.top() + rect.height() * .72))
        painter.drawLine(QPointF(rect.left() + rect.width() * .43, rect.top() + rect.height() * .72),
                         QPointF(rect.left() + rect.width() * .78, rect.top() + rect.height() * .28))
        painter.end()


class OrganizationTokenDialog(QDialog):
    def __init__(self, parent=None, *, theme=None):
        super().__init__(parent)
        self.setObjectName("organizationDialog")
        self.setWindowTitle("Configure Organization Tokens")
        self.setMinimumWidth(600)
        self.tokens = None
        inherited = parent.property("ericaTheme") if parent is not None else None
        mode = theme or inherited
        if mode not in ("dark", "light"):
            mode = "dark" if self.palette().color(QPalette.ColorRole.Window).lightness() < 128 else "light"
        self.setProperty("ericaTheme", mode)
        self._apply_theme(mode)

        layout = QVBoxLayout(self)
        layout.setContentsMargins(20, 20, 20, 20)
        layout.setSpacing(12)
        title = QLabel("Organization tokens")
        title.setObjectName("organizationTitle")
        layout.addWidget(title)
        explanation = QLabel(
            "Use the same two tokens, in the same order, on each authorized PC. "
            "Erica generates a read-only, five-digit check for each token. "
            "Compare checks with your administrator's trusted backup."
        )
        explanation.setWordWrap(True)
        layout.addWidget(explanation)
        layout.addSpacing(4)

        form = QFormLayout()
        form.setHorizontalSpacing(16)
        form.setVerticalSpacing(10)
        form.setLabelAlignment(Qt.AlignmentFlag.AlignLeft | Qt.AlignmentFlag.AlignVCenter)
        form.setFieldGrowthPolicy(QFormLayout.FieldGrowthPolicy.AllNonFixedFieldsGrow)
        self.token_inputs = []
        self.token_warnings = []
        self.check_inputs = []
        self.copy_buttons = []
        for index in range(2):
            token = QLineEdit()
            token.setEchoMode(QLineEdit.EchoMode.Password)
            token.setPlaceholderText("Exactly 16 digits (0-9)")
            token.setAccessibleName(f"Token {index + 1}")
            token.setAccessibleDescription("Requires exactly 16 ASCII digits, 0 through 9. Leading zeros matter.")
            token.setToolTip("Requires exactly 16 digits (0-9). Leading zeros are significant.")
            hint = QLabel("Requires exactly 16 digits (0-9). Leading zeros matter.")
            hint.setObjectName(f"tokenWarning{index + 1}")
            hint.setProperty("status", "hint")
            hint.setWordWrap(True)
            hint.setAccessibleName(f"Token {index + 1} validation message")
            token_row = QVBoxLayout()
            token_row.setContentsMargins(0, 0, 0, 0)
            token_row.setSpacing(4)
            token_row.addWidget(token)
            token_row.addWidget(hint)
            token_label = QLabel(f"Token &{index + 1}:")
            token_label.setBuddy(token)
            form.addRow(token_label, token_row)
            check = QLineEdit()
            check.setObjectName("organizationCheck")
            check.setReadOnly(True)
            check.setPlaceholderText("5-digit check")
            check.setAccessibleName(f"Token {index + 1} check value")
            check.setToolTip("Five digits generated by Erica in Rust. Read-only; compare with your trusted backup.")
            copy = QPushButton("Copy")
            copy.setEnabled(False)
            copy.setAutoDefault(False)
            copy.setAccessibleName(f"Copy token {index + 1} check value")
            copy.setToolTip("Copy this check value. Clipboard history may retain it.")
            copy.clicked.connect(lambda checked=False, i=index: self._copy_check(i))
            check_row = QHBoxLayout()
            check_row.setContentsMargins(0, 0, 0, 0)
            check_row.setSpacing(8)
            check_row.addWidget(check, 1)
            check_row.addWidget(copy)
            check_label = QLabel(f"Check value {index + 1}:")
            check_label.setBuddy(check)
            form.addRow(check_label, check_row)
            self.token_inputs.append(token)
            self.token_warnings.append(hint)
            self.check_inputs.append(check)
            self.copy_buttons.append(copy)
            token.textChanged.connect(lambda text, i=index: self._refresh_check(i, text))
        layout.addLayout(form)
        self.show_tokens = _VisibleCheckBox("Show tokens (keep your screen private)")
        self.show_tokens.setObjectName("showTokenToggle")
        self.show_tokens.setProperty("checkmarkColor", self._checkmark_color)
        self.show_tokens.setToolTip("Show or hide both tokens. New generated tokens are shown automatically.")
        self.show_tokens.toggled.connect(self._set_visible)
        layout.addWidget(self.show_tokens)
        generate = QPushButton("Generate a new organization token pair")
        generate.setAutoDefault(False)
        generate.clicked.connect(self.generate_pair)
        layout.addWidget(generate)

        warning = QLabel(
            "Important: generating a pair creates a NEW organization. Back up both "
            "tokens and checks securely. Lost tokens cannot be recovered; replacing "
            "them does not convert old files. Anyone with both tokens can open the "
            "files. Five-digit checks can collide: they detect some entry mistakes, "
            "not identity or authorization. This is not a hardware HSM. Keep checks "
            "private; they allow token guesses to be tested offline."
        )
        warning.setObjectName("organizationNotice")
        warning.setWordWrap(True)
        layout.addWidget(warning)
        self.backed_up = _VisibleCheckBox("I have securely backed up both tokens and checks.")
        self.backed_up.setProperty("checkmarkColor", self._checkmark_color)
        layout.addWidget(self.backed_up)
        buttons = QDialogButtonBox(
            QDialogButtonBox.StandardButton.Save | QDialogButtonBox.StandardButton.Cancel
        )
        buttons.button(QDialogButtonBox.StandardButton.Save).setObjectName("organizationSave")
        buttons.accepted.connect(self.validate_and_accept)
        buttons.rejected.connect(self.reject)
        layout.addWidget(buttons)
        self.resize(680, self.sizeHint().height())

    def _apply_theme(self, mode):
        # Match the editor's restrained neutral palette without colored panels.
        if mode == "dark":
            background, surface, text, muted = "#252526", "#303033", "#F0F0F0", "#BCBDC3"
            accent, accent_text, border, hover = "#8AB4F8", "#182337", "#73737B", "#AACAFB"
            error, ready = "#FFB4AB", "#B8D8B3"
        else:
            background, surface, text, muted = "#F0F0F0", "#FFFFFF", "#202124", "#555A63"
            accent, accent_text, border, hover = "#245EA8", "#FFFFFF", "#92969E", "#1C4B87"
            error, ready = "#A12622", "#326438"
